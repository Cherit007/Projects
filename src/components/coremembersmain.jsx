const CoreMembersMain = () => {
  const [currentIndex, setCurrentIndex] = useState(0);
  const [visibleMembers, setVisibleMembers] = useState([]);
  const navigate = useNavigate();
  const [isMobile, setIsMobile] = useState(window.innerWidth < 768); // Check screen width

  const itemsPerPage = isMobile ? 1 : 3; // Show 1 card on mobile, 3 cards on larger devices
  const totalPages = Math.ceil(membersData.length / itemsPerPage); // Dynamically calculated

  // Next slide
  useEffect(() => {
    const interval = setInterval(() => {
      setCurrentIndex((prev) => (prev + 1) % totalPages);
    }, 5000); // Auto-scroll every 5 seconds

    return () => clearInterval(interval);
  }, [currentIndex, totalPages]);
  const nextSlide = () => {
    setCurrentIndex((prev) => (prev + 1) % totalPages);
  };

  // Previous slide
  const prevSlide = () => {
    setCurrentIndex((prev) => (prev === 0 ? totalPages - 1 : prev - 1));
  };

  // Handle window resize
  useEffect(() => {
    const handleResize = () => {
      setIsMobile(window.innerWidth < 768);
    };

    window.addEventListener('resize', handleResize);
    return () => window.removeEventListener('resize', handleResize);
  }, []);

  // Update visible members when currentIndex, itemsPerPage, or membersData changes
  useEffect(() => {
    const startIndex = currentIndex * itemsPerPage;
    const endIndex = startIndex + itemsPerPage;
    setVisibleMembers(membersData.slice(startIndex, endIndex));
  }, [currentIndex, itemsPerPage, membersData]);


  return (
    <div className="core-members">
      <h2 className="core-members-heading">मुख्य समिति सदस्य</h2>
      <p className="core-members-subtext">
        हमारे प्रतिभाशाली और समर्पित टीम सदस्यों से मिलिए।
      </p>

      <div className="scrollable-banner-container">
        <button className="nav-button left" onClick={prevSlide}>
          <FaArrowLeft />
        </button>

        <div className="scrollable-banner">
          {visibleMembers.map((member) => (
            <div key={member.id} className="member-card">
              <div className="member-image-container">
                <img
                  src={member.image}
                  alt={member.name}
                  className="member-image"
                />
              </div>
              <p className="member-name">{member.name}</p>
              <p className="member-designation">{member.designation}</p>
              <button
                className="show-more-button"
                onClick={() =>
                  navigate(`/core-member/${member.id}`, { state: { member } })
                }
              >
                View More
              </button>
            </div>
          ))}
        </div>

        <button className="nav-button right" onClick={nextSlide}>
          <FaArrowRight />
        </button>
      </div>
    </div>
  );
};

export default CoreMembersMain;
