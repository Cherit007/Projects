// Builds src/services/statements/pdfReaderHtml.ts: a self-contained page that
// reads the text of a PDF with PDF.js inside a WebView, so bank statements are
// read on the phone without any network access.
//
//   node scripts/build-pdf-reader.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const build = path.join(root, 'node_modules/pdfjs-dist/legacy/build');
const { version } = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/pdfjs-dist/package.json'), 'utf8'));

const inline = file => fs.readFileSync(path.join(build, file), 'utf8').replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

// The worker runs on the page's thread: PDF.js uses globalThis.pdfjsWorker when it is defined.
const reader = `
(function () {
  function post(message) { window.ReactNativeWebView.postMessage(JSON.stringify(message)); }
  window.readPdf = async function (id, base64, password) {
    try {
      var binary = atob(base64);
      var data = new Uint8Array(binary.length);
      for (var i = 0; i < binary.length; i++) data[i] = binary.charCodeAt(i);
      var doc = await pdfjsLib.getDocument({
        data: data,
        password: password,
        isEvalSupported: false,
        disableFontFace: true,
        disableAutoFetch: true,
        disableStream: true,
      }).promise;
      var pages = [];
      for (var n = 1; n <= doc.numPages; n++) {
        var page = await doc.getPage(n);
        var content = await page.getTextContent();
        pages.push(content.items.filter(function (item) { return item.str && item.str.trim(); }).map(function (item) {
          return { s: item.str, x: Math.round(item.transform[4]), y: Math.round(item.transform[5]), w: Math.round(item.width) };
        }));
        page.cleanup();
      }
      await doc.destroy();
      post({ id: id, type: 'pages', pages: pages });
    } catch (error) {
      if (error && error.name === 'PasswordException') {
        post({ id: id, type: error.code === 2 ? 'wrong-password' : 'needs-password' });
      } else {
        post({ id: id, type: 'error', message: String((error && error.message) || error) });
      }
    }
  };
  post({ type: 'ready' });
})();
`;

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'">
</head><body>
<script>${inline('pdf.worker.min.js')}</script>
<script>${inline('pdf.min.js')}</script>
<script>${reader}</script>
</body></html>`;

const out = path.join(root, 'src/services/statements/pdfReaderHtml.ts');
fs.writeFileSync(
  out,
  `// Generated by scripts/build-pdf-reader.mjs from pdfjs-dist ${version}. Do not edit.\n` +
    `export const PDF_READER_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Wrote ${path.relative(root, out)} (${Math.round(html.length / 1024)} KB)`);
