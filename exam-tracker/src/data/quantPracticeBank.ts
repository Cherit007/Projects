/** Original exam-style Quant drills (not verbatim copyrighted PYQs). */

export type PracticeDifficulty = 'easy' | 'moderate' | 'hard'

export type PracticeQuestion = {
  id: string
  topicId: string
  stem: string
  passage?: string
  options: Array<{ id: string; text: string }>
  answerId: string
  explanation: string
  difficulty: PracticeDifficulty
}

export const QUANT_SECTION_IDS = [
  'qa-number-system',
  'qa-percent-pl',
  'qa-si-ci',
  'qa-ratio',
  'qa-time-work',
  'qa-speed',
  'qa-mensuration',
  'qa-algebra',
  'qa-permutation',
  'qa-di',
  'qa-ds',
] as const

export type QuantSectionId = (typeof QUANT_SECTION_IDS)[number]

const ids = ['a', 'b', 'c', 'd'] as const

function q(args: {
  id: string
  topicId: string
  stem: string
  passage?: string
  options: [string, string, string, string]
  answer: 0 | 1 | 2 | 3
  explanation: string
  difficulty: PracticeDifficulty
}): PracticeQuestion {
  const options = args.options.map((text, i) => ({ id: ids[i], text }))
  return {
    id: args.id,
    topicId: args.topicId,
    stem: args.stem,
    passage: args.passage,
    options,
    answerId: options[args.answer].id,
    explanation: args.explanation,
    difficulty: args.difficulty,
  }
}

