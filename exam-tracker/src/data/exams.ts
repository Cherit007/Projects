export const EXAM_BY_ID: Record<string, Exam> = Object.fromEntries(
  EXAMS.map((e) => [e.id, e]),
)

export function examTopicIds(exam: Exam): string[] {
  return [...new Set(exam.syllabus.flatMap((s) => s.topicIds))]
}

export function examsSharingTopic(topicId: string): Exam[] {
  return EXAMS.filter((e) => examTopicIds(e).includes(topicId))
}
